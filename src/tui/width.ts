const SEGMENTER_ZERO_FLAG = "\u20e3"; // keycap combiner

function inRanges(cp: number, ranges: ReadonlyArray<readonly [number, number]>): boolean {
  // binary search (ranges are sorted and non-overlapping)
  let lo = 0, hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [a, b] = ranges[mid];
    if (cp < a) hi = mid - 1;
    else if (cp > b) lo = mid + 1;
    else return true;
  }
  return false;
}

function graphemeWidth(grapheme: string): number {
  if (!grapheme) return 0;
  const first = grapheme.codePointAt(0)!;
  if (first >= 0xfe00 && first <= 0xfe0f) return 0; // variation selectors alone
  if (first === 0x200d) return 0;
  if (/^[\p{Mn}\p{Me}\p{Cf}]/u.test(grapheme)) return 0; // residual combining chars
  if (grapheme.includes("\u200d")) return 2; // ZWJ emoji sequence
  if (inRanges(first, ZERO_RANGES)) return 0;
  if (inRanges(first, WIDE_RANGES)) return 2;
  if (first >= 0x300 && first <= 0x36f) return 0;
  if ((first >= 0x1f300 && first <= 0x1faff) || (first >= 0x2600 && first <= 0x27bf)) return 2;
  return 1;
}

export function visibleWidth(text: string): number {
  if (!text) return 0;
  const stripped = stripAnsi(text);
  let width = 0;
  for (const g of splitGraphemes(stripped)) width += graphemeWidth(g);
  return width;
}

export function stripAnsi(text: string): string {
  return text.replace(/\x1b\[[0-9;?]*[a-zA-Z]|\x1b\][^\x07]*\x07/g, "");
}

export function graphemeSlice(text: string, maxWidth: number): string {
  let width = 0;
  let out = "";
  for (const g of splitGraphemes(text)) {
    const w = graphemeWidth(g);
    if (width + w > maxWidth) break;
    out += g;
    width += w;
  }
  return out;
}
