// Grapheme-aware terminal display width measurement (ANSI-aware).
// Uses Intl.Segmenter for grapheme clusters; approximates Unicode East-Asian
// width rules and zero-width combining marks, good enough for alignment and wrapping.

const segmenter = typeof Intl !== "undefined" && typeof (Intl as any).Segmenter === "function"
  ? new (Intl as any).Segmenter("en", { granularity: "grapheme" })
  : null;

export function splitGraphemes(text: string): string[] {
  if (segmenter) {
    return Array.from(segmenter.segment(text), (s: any) => s.segment);
  }
  return Array.from(text); // fallback: code points (loses ZWJ joining)
}

